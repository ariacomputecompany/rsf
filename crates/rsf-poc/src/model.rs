use std::fmt;

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub enum ImplementationId {
    UniversalVsrRados,
    FoundationDbExtent,
    AuroraSocrates,
    GeoLocalWpaxos,
    DualModeCpAp,
}

impl ImplementationId {
    pub fn slug(self) -> &'static str {
        match self {
            Self::UniversalVsrRados => "universal-vsr-rados",
            Self::FoundationDbExtent => "foundationdb-extent",
            Self::AuroraSocrates => "aurora-socrates",
            Self::GeoLocalWpaxos => "geo-local-wpaxos",
            Self::DualModeCpAp => "dual-mode-cp-ap",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "universal-vsr-rados" => Some(Self::UniversalVsrRados),
            "foundationdb-extent" => Some(Self::FoundationDbExtent),
            "aurora-socrates" => Some(Self::AuroraSocrates),
            "geo-local-wpaxos" => Some(Self::GeoLocalWpaxos),
            "dual-mode-cp-ap" => Some(Self::DualModeCpAp),
            _ => None,
        }
    }
}

impl fmt::Display for ImplementationId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.slug())
    }
}

